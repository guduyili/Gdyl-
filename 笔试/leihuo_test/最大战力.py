import sys

def main():
    """
    0/1 背包问题：给定 N 件物品，每件有费用 cost 和战力 power，
    总金币为 B，求在总费用不超过 B 的前提下，能获得的最大战力总和。
    采用一维动态规划数组，空间复杂度 O(B)，时间复杂度 O(N*B)。
    """

    # ------------------- 输入处理 -------------------
    # 使用 sys.stdin.readline() 按行读取，避免交互式终端下因 read() 等待 EOF 而卡住。
    first_line = sys.stdin.readline()
    if not first_line:          # 若没有输入则直接返回
        return

    # 第一行：N 和 B
    N, B = map(int, first_line.split())

    # dp[j] 表示“当前已经处理完部分物品后，花费恰好为 j 金币时所能获得的最大战力”。
    # 数组长度为 B+1，初始化全 0，表示不选任何物品时，任意花费下的战力均为 0。
    # 注意：此处实际表示“花费不超过 j”，但倒序更新时，我们使用“花费恰好”的方式，
    # 最终 dp[B] 也等价于不超过 B 的最大值，因为未使用的容量不会带来收益。
    dp = [0] * (B + 1)

    # 依次处理 N 个物品
    for i in range(N):
        # 读取当前物品的费用 c 和战力 p
        c, p = map(int, sys.stdin.readline().split())

        # 内层循环：为了确保每个物品只能选一次，必须倒序遍历 j 从 B 到 c
        # 如果正序更新，则当前物品会被重复使用（完全背包），不符合题意。
        # 我们只考虑 j >= c 的状态，因为费用不够时无法转移。
        for j in range(B, c - 1, -1):
            # 状态转移方程：dp[j] = max(dp[j], dp[j - c] + p)
            # 表示“花费 j”的最大战力 = 不选当前物品（保持原值） vs 选当前物品（花费 j-c 时的战力 + 当前战力）的较大者。
            if dp[j - c] + p > dp[j]:
                dp[j] = dp[j - c] + p

    # 最终 dp[B] 即为总费用不超过 B 时的最大战力（由于 dp 数组在更新过程中始终保留最优值，且容量可剩余，故 dp[B] 即为答案）
    print(dp[B])


if __name__ == "__main__":
    main()